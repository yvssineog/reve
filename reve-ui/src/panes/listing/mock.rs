// An instruction row.
const fn code(
    address: u32,
    bytes: &'static str,
    mnemonic: &'static str,
    operands: Operands,
    eol: Option<Eol>,
) -> Row {
    Row::Code(Code {
        address,
        bytes,
        mnemonic,
        operands,
        eol,
    })
}

// Copies of the template, so the listing runs past a million rows.
const COPIES: u32 = 3400;
// Where each copy starts after the last, past the template's 0x4e34 bytes.
const SPAN: u32 = 0x10000;

// TODO: the Ghidra adapter should lay rows out from `reve_model::Program` instead of this mock.
// The template, copied COPIES times with its addresses moved up a SPAN each time. XREF text
// keeps the first copy's addresses.
pub fn rows() -> Vec<Row> {
    (0..COPIES)
        .flat_map(|copy| TEMPLATE.iter().map(move |&row| shifted(row, copy * SPAN)))
        .collect()
}

// `row` with its address, and its call's target, moved up `by`.
fn shifted(mut row: Row, by: u32) -> Row {
    if let Row::Code(code) = &mut row {
        code.address += by;
        if let Operands::Call(_, entry) = &mut code.operands {
            *entry += by;
        }
    }
    row
}

